/// 二つ名メーカーの診断を生成する。
MakerResult generateFutatsuna(String input, Random random) {
  final adjective = _adjectives[random.nextInt(_adjectives.length)];
  final noun = _nouns[random.nextInt(_nouns.length)];
  final flavor = pickTwoSentences(random, _flavorOpeners, _flavorClosers);
  final title = '$adjective$noun';

  return MakerResult(
    category: MakerCategory.futatsuna,
    input: input,
    headline: '『$input』の二つ名は──',
    answer: title,
    detail: flavor,
    shareText: '【二つ名メーカー】「$input」の二つ名は『$title』でした。',
  );
}
