  final noun = _nouns[random.nextInt(_nouns.length)];
  final flavor = _flavorLines[random.nextInt(_flavorLines.length)];
  final title = '$adjective$noun';

  return MakerResult(
    category: MakerCategory.futatsuna,
    input: input,
    headline: '『$input』の二つ名は──',
    answer: title,
    detail: flavor,
    shareText: '【二つ名メーカー】「$input」の二つ名は『$title』でした。',
  );
}
