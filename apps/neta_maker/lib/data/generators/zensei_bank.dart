/// 前世メーカーの診断を生成する。
MakerResult generateZensei(String input, Random random) {
  final era = _eras[random.nextInt(_eras.length)];
  final role = _roles[random.nextInt(_roles.length)];
  final episode = _episodes[random.nextInt(_episodes.length)];

  return MakerResult(
    category: MakerCategory.zensei,
    input: input,
    headline: '『$input』の前世を視ています──',
    answer: '$eraの$role',
    detail: episode,
    shareText: '【前世メーカー】「$input」の前世は「$eraの$role」でした。',
  );
}
