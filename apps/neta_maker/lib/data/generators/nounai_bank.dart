/// 脳内メーカーの診断を生成する。
MakerResult generateNounai(String input, Random random) {
  final keywords = pickDistinct(random, _keywordPool, 4);
  final average =
      keywords.map((k) => k.instinctRatio).reduce((a, b) => a + b) /
      keywords.length;

  final List<String> openerPool;
  final List<String> closerPool;
  final String tendencyLabel;
  if (average < 0.4) {
    openerPool = _logicalOpeners;
    closerPool = _logicalClosers;
    tendencyLabel = '理性型';
  } else if (average < 0.6) {
    openerPool = _balancedOpeners;
    closerPool = _balancedClosers;
    tendencyLabel = 'バランス型';
  } else {
    openerPool = _instinctiveOpeners;
    closerPool = _instinctiveClosers;
    tendencyLabel = '本能型';
  }
  final comment = pickTwoSentences(random, openerPool, closerPool);

  return MakerResult(
    category: MakerCategory.nounai,
    input: input,
    headline: '『$input』の脳内をのぞくと──',
    answer: tendencyLabel,
    detail: comment,
    shareText: '【脳内メーカー】「$input」の脳内は$tendencyLabelでした。',
    keywords: keywords,
  );
}
