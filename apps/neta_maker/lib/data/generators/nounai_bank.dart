/// 脳内メーカーの診断を生成する。
MakerResult generateNounai(String input, Random random) {
  final keywords = pickDistinct(random, _keywordPool, 4);
  final average =
      keywords.map((k) => k.instinctRatio).reduce((a, b) => a + b) /
      keywords.length;

  final List<String> commentPool;
  final String tendencyLabel;
  if (average < 0.4) {
    commentPool = _logicalComments;
    tendencyLabel = '理性型';
  } else if (average < 0.6) {
    commentPool = _balancedComments;
    tendencyLabel = 'バランス型';
  } else {
    commentPool = _instinctiveComments;
    tendencyLabel = '本能型';
  }
  final comment = commentPool[random.nextInt(commentPool.length)];

  return MakerResult(
    category: MakerCategory.nounai,
    input: input,
    headline: '『$input』の脳内をのぞくと──',
    answer: tendencyLabel,
    detail: comment,
    shareText: '【脳内メーカー】「$input」の脳内は$tendencyLabelでした。',
    keywords: keywords,
  );
}
